import { test, expect } from "@playwright/test";
import { mkdirSync } from "node:fs";

const origin = "http://127.0.0.1:3001";
test("coupon and points reach the payment receipt and cancellation returns the points", async ({ page }) => {
  const login = await page.request.post("/api/auth/demo", { headers: { origin }, data: { account: "customer" } });
  expect(login.ok()).toBeTruthy();
  const before = await (await page.request.get("/api/rewards")).json();
  expect(before.balance).toBeGreaterThan(0);
  await page.goto("/");
  await page.getByRole("button", { name: "Add Chicken dum biryani", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: /Add to order/ }).click();
  await page.locator(".cart-line").getByRole("button", { name: "Add one Chicken dum biryani" }).click();
  await page.getByRole("link", { name: "Continue to checkout" }).click();
  await page.getByLabel("Mobile number").fill("9000000000");
  await page.getByLabel("Coupon code").fill("EXPIRED10");
  await page.getByRole("button", { name: "Apply", exact: true }).click();
  await expect(page.getByText("This coupon is not currently available")).toBeVisible();
  await page.getByLabel("Coupon code").fill("BIRYANI10");
  await page.getByRole("button", { name: "Apply", exact: true }).click();
  await expect(page.getByText(/BIRYANI10 applied/)).toBeVisible();
  await page.getByLabel("Use my loyalty points").check();
  await expect(page.getByRole("button", { name: /Continue to payment/ })).toBeEnabled();
  const expectedPoints = Math.min(before.balance, 115);
  mkdirSync(".local/screenshots", { recursive: true });
  await page.screenshot({ path: ".local/screenshots/checkout-rewards-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: ".local/screenshots/checkout-rewards-mobile.png", fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.getByRole("button", { name: /Continue to payment/ }).click();
  await expect(page).toHaveURL(/\/payment\//);
  const id = new URL(page.url()).pathname.split("/").pop()!;
  const order = await (await page.request.get(`/api/orders/${id}`)).json();
  expect(order.subtotalPaise).toBe(64000);
  expect(order.couponDiscountPaise).toBe(6400);
  expect(order.redeemedPoints).toBe(expectedPoints);
  expect(order.totalPaise).toBe(57600 - expectedPoints * 100);
  await page.getByRole("button", { name: /Pay ₹/ }).click();
  await expect(page).toHaveURL(/\/orders\/[^/]+$/);
  await expect(page.getByText(`${expectedPoints} loyalty points`, { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Cancel order & request refund" }).click();
  await expect(page.getByText(`Your ${expectedPoints} reserved points have been returned.`)).toBeVisible();
  const after = await (await page.request.get("/api/rewards")).json();
  expect(after.balance).toBe(before.balance);
  await page.goto("/orders");
  await expect(page.getByRole("region", { name: "Your loyalty rewards" })).toBeVisible();
  await page.getByText("Points activity", { exact: true }).click();
  const returned = page.getByRole("region", { name: "Your loyalty rewards" })
    .getByRole("listitem").filter({ hasText: order.number }).filter({ hasText: "Points returned" });
  await expect(returned).toBeVisible();
  await expect(returned).toContainText(`+${expectedPoints}`);
  await page.screenshot({ path: ".local/screenshots/rewards-wallet-mobile.png", fullPage: true });
});
